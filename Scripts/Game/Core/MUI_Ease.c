class MUI_Ease
{
	//------------------------------------------------------------------------------------------------
	static float Clamp01(float t)
	{
		if (t < 0)
			return 0;
		if (t > 1)
			return 1;
		return t;
	}

	//------------------------------------------------------------------------------------------------
	static float Linear(float t)
	{
		return Clamp01(t);
	}

	//------------------------------------------------------------------------------------------------
	static float CubicOut(float t)
	{
		t = Clamp01(t);
		float u = 1.0 - t;
		return 1.0 - u * u * u;
	}

	//------------------------------------------------------------------------------------------------
	static float CubicInOut(float t)
	{
		t = Clamp01(t);
		if (t < 0.5)
			return 4.0 * t * t * t;
		float u = -2.0 * t + 2.0;
		return 1.0 - (u * u * u) * 0.5;
	}

	//------------------------------------------------------------------------------------------------
	static float BackOut(float t)
	{
		t = Clamp01(t);
		float c1 = 1.70158;
		float c3 = c1 + 1.0;
		float u = t - 1.0;
		return 1.0 + c3 * u * u * u + c1 * u * u;
	}

	//------------------------------------------------------------------------------------------------
	static float Approach(float value, float target, float dt, float speed)
	{
		float k = dt * speed;
		if (k > 1)
			k = 1;
		if (k < 0)
			k = 0;
		return value + (target - value) * k;
	}

	//------------------------------------------------------------------------------------------------
	static float Fract(float v)
	{
		return v - Math.Floor(v);
	}

	//------------------------------------------------------------------------------------------------
	static float Pulse(float time, float hz)
	{
		return 0.5 + 0.5 * Math.Sin(time * hz * Math.PI2);
	}
}
